/**
 * Universal translation function retrieving translated string for any language code
 */
export const t = (lang: LanguageCode, key: string, fallback?: string): string => {
  const targetDict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  if (targetDict && targetDict[key]) {
    return targetDict[key];
  }
  const enDict = TRANSLATIONS['en'];
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
};
